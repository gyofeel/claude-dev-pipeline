#!/usr/bin/env node
/**
 * commit-msg-check — dry-runs the project's own commit-msg hook on a message file, so the hook
 * (not prose rules) decides whether the session's commit trailer may be used.
 *
 * Usage: node commit-msg-check.mjs <message-file> [--repo <dir>]
 * stdout: { ok, hook, trailerDropped, message, output } — exit 0 always.
 */
import { spawnSync } from 'node:child_process';
import { accessSync, constants, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';

const HOOK_TIMEOUT_MS = 30000;
const args = process.argv.slice(2);
const flag = (name) => {
    const i = args.indexOf(name);
    return i === -1 ? null : args[i + 1];
};
const msgFile = args.find((a, i) => !a.startsWith('--') && args[i - 1] !== '--repo');
const repo = path.resolve(flag('--repo') || process.cwd());

const git = (...a) => {
    const r = spawnSync('git', a, { cwd: repo, encoding: 'utf8' });
    if (r.error) throw r.error;
    return r.stdout.trim();
};

const findHook = () => {
    const hooksPath = git('config', 'core.hooksPath');
    const dir = hooksPath
        ? path.resolve(git('rev-parse', '--show-toplevel') || repo, hooksPath)
        : path.resolve(repo, git('rev-parse', '--git-path', 'hooks'));
    const hook = path.join(dir, 'commit-msg');
    try {
        if (!statSync(hook).isFile()) return null;
        accessSync(hook, constants.X_OK);
        return hook;
    } catch {
        return null;
    }
};

const TRAILER_LINE = /^(co-authored-by:|generated with \[|generated by claude|🤖)/i;
// Only trailing paragraphs made entirely of trailer lines go; the subject paragraph never does.
const dropTrailers = (text) => {
    const paras = text.trimEnd().split(/\n\s*\n/);
    while (paras.length > 1 && paras.at(-1).split('\n').every((l) => TRAILER_LINE.test(l.trim()))) paras.pop();
    return `${paras.join('\n\n')}\n`;
};

const runHook = (hook, message, tmp) => {
    const file = path.join(tmp, 'COMMIT_EDITMSG');
    writeFileSync(file, message);
    const r = spawnSync(hook, [file], { cwd: repo, encoding: 'utf8', timeout: HOOK_TIMEOUT_MS });
    const note = r.error ? (r.error.code === 'ETIMEDOUT' ? `hook timed out after ${HOOK_TIMEOUT_MS} ms` : r.error.message) : '';
    return {
        ok: !r.error && r.status === 0,
        output: [r.stdout, r.stderr, note].filter(Boolean).join(''),
        message: readFileSync(file, 'utf8')
    };
};

const check = () => {
    if (!msgFile) throw new Error('usage: commit-msg-check.mjs <message-file> [--repo <dir>]');
    const original = readFileSync(msgFile, 'utf8');
    const hook = findHook();
    if (!hook) return { ok: true, hook: null, trailerDropped: false, message: original, output: '' };
    const tmp = mkdtempSync(path.join(tmpdir(), 'commit-msg-check-'));
    try {
        const first = runHook(hook, original, tmp);
        if (first.ok) return { ok: true, hook, trailerDropped: false, message: first.message, output: first.output };
        const stripped = dropTrailers(original);
        const fail = (output) => ({ ok: false, hook, trailerDropped: false, message: original, output });
        if (stripped === original) return fail(first.output);
        const second = runHook(hook, stripped, tmp);
        return second.ok
            ? { ok: true, hook, trailerDropped: true, message: second.message, output: second.output }
            : fail(first.output + second.output);
    } finally {
        rmSync(tmp, { recursive: true, force: true });
    }
};

let result;
try {
    result = check();
} catch (e) {
    result = { ok: false, hook: null, trailerDropped: false, message: '', output: String(e.message || e) };
}
console.log(JSON.stringify(result));
