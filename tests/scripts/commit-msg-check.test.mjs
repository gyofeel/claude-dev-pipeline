import { test, after } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { chmodSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';

const SCRIPT = path.resolve('scripts/commit-msg-check.mjs');
const dirs = [];
after(() => dirs.forEach((d) => rmSync(d, { recursive: true, force: true })));

const MSG = 'Add thing\n\nbody line\n\nCo-Authored-By: Bot <bot@example.com>\n';

const setup = (hookBody, { dir = '.git/hooks', mode = 0o755 } = {}) => {
    const repo = mkdtempSync(path.join(tmpdir(), 'cmcheck-'));
    dirs.push(repo);
    execFileSync('git', ['init', '-q'], { cwd: repo });
    const msgFile = path.join(repo, 'msg.txt');
    writeFileSync(msgFile, MSG);
    if (hookBody !== null) {
        mkdirSync(path.join(repo, dir), { recursive: true });
        const hook = path.join(repo, dir, 'commit-msg');
        writeFileSync(hook, `#!/bin/sh\n${hookBody}\n`);
        chmodSync(hook, mode);
    }
    return { repo, msgFile };
};
const run = ({ repo, msgFile }) =>
    JSON.parse(execFileSync('node', [SCRIPT, msgFile, '--repo', repo], { encoding: 'utf8' }));

test('no hook: ok, message unchanged', () => {
    const r = run(setup(null));
    assert.deepEqual([r.ok, r.hook, r.trailerDropped, r.message], [true, null, false, MSG]);
});

test('hook rejecting Co-Authored-By: trailer dropped, rest unchanged', () => {
    const r = run(setup('grep -qi "^Co-Authored-By" "$1" && { echo "AI trailer forbidden" >&2; exit 1; }; exit 0'));
    assert.equal(r.ok, true);
    assert.equal(r.trailerDropped, true);
    assert.ok(!/Co-Authored-By/i.test(r.message));
    assert.equal(r.message.trimEnd(), 'Add thing\n\nbody line');
});

test('hook rejecting everything: ok false with output', () => {
    const r = run(setup('echo "nope, bad subject" >&2; exit 1'));
    assert.equal(r.ok, false);
    assert.match(r.output, /nope, bad subject/);
});

test('core.hooksPath is honoured', () => {
    const s = setup('echo "husky says no" >&2; exit 1', { dir: '.husky' });
    execFileSync('git', ['config', 'core.hooksPath', '.husky'], { cwd: s.repo });
    const r = run(s);
    assert.equal(r.ok, false);
    assert.match(r.hook, /\.husky\/commit-msg$/);
    assert.match(r.output, /husky says no/);
});

test('hook rewriting the file: rewritten message returned, caller file untouched', () => {
    const s = setup('printf "rewritten\\n" > "$1"');
    const r = run(s);
    assert.equal(r.ok, true);
    assert.equal(r.message, 'rewritten\n');
    assert.equal(readFileSync(s.msgFile, 'utf8'), MSG);
});

test('non-executable hook is treated as no hook', () => {
    const r = run(setup('exit 1', { mode: 0o644 }));
    assert.deepEqual([r.ok, r.hook], [true, null]);
});

test('legitimate subject/body lines starting with Generated survive trailer dropping', () => {
    const s = setup('grep -q "^Co-Authored-By" "$1" && exit 1; exit 0');
    writeFileSync(s.msgFile, 'Generated by codegen: update\n\nGenerated with care by hand.\n\nCo-Authored-By: Bot <b@e.com>\n');
    const r = run(s);
    assert.equal(r.trailerDropped, true);
    assert.equal(r.message.trimEnd(), 'Generated by codegen: update\n\nGenerated with care by hand.');
});

test('multi-line AI trailer block is removed', () => {
    const s = setup('grep -qE "Co-Authored-By|Generated with" "$1" && exit 1; exit 0');
    writeFileSync(s.msgFile, 'Subject\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\nCo-Authored-By: Bot <b@e.com>\n');
    assert.equal(run(s).message.trimEnd(), 'Subject');
});

test('rejection unrelated to trailers is not retried (output not duplicated)', () => {
    const s = setup('echo "bad subject" >&2; exit 1');
    writeFileSync(s.msgFile, 'Subject only\n');
    assert.equal(run(s).output.match(/bad subject/g).length, 1);
});

test('missing message file: exit 0 with ok:false JSON', () => {
    const s = setup(null);
    const r = run({ repo: s.repo, msgFile: path.join(s.repo, 'nope.txt') });
    assert.deepEqual([r.ok, r.hook, r.trailerDropped, r.message], [false, null, false, '']);
    assert.ok(r.output.length > 0);
});

test('missing argument: exit 0 with ok:false JSON', () => {
    const r = JSON.parse(execFileSync('node', [SCRIPT], { encoding: 'utf8' }));
    assert.equal(r.ok, false);
});

test('hook with a bad shebang reports the spawn error', () => {
    const s = setup(null);
    mkdirSync(path.join(s.repo, '.git/hooks'), { recursive: true });
    const hook = path.join(s.repo, '.git/hooks/commit-msg');
    writeFileSync(hook, '#!/no/such/interpreter\n');
    chmodSync(hook, 0o755);
    const r = run(s);
    assert.equal(r.ok, false);
    assert.match(r.output, /ENOENT|spawn/);
});

test('linked worktree finds the hook via git-path', () => {
    const s = setup('echo "wt hook" >&2; exit 1');
    execFileSync('git', ['-c', 'user.name=t', '-c', 'user.email=t@e.com', 'commit', '-q', '--no-verify', '--allow-empty', '-m', 'init'], { cwd: s.repo });
    const wt = path.join(s.repo, '..', path.basename(s.repo) + '-wt');
    dirs.push(wt);
    execFileSync('git', ['worktree', 'add', '-q', wt], { cwd: s.repo });
    const r = run({ repo: wt, msgFile: s.msgFile });
    assert.equal(r.ok, false);
    assert.match(r.output, /wt hook/);
});
